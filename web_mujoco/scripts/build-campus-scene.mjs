import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CAMPUS_LAYOUT, CAMPUS_BUILDINGS, CAMPUS_PROPS } from '../src/campus-layout.js';

const models = new URL('../../rebotarm_mujoco_rs/models/', import.meta.url);
let xml = await readFile(new URL('rs_agv_scene.xml', models), 'utf8');
const number = (n) => Number(n.toFixed(6));
const vector = (values) => values.map(number).join(' ');
const [floorX, floorY] = CAMPUS_LAYOUT.floorHalfSize;
const geom = (name, position, size, attrs = '') =>
  `    <geom name="${name}" type="box" pos="${vector(position)}" size="${vector(size)}" ${attrs} />`;
const objects = CAMPUS_BUILDINGS.map((item) => geom(
  item.id, [item.x, item.y, item.height / 2], [item.halfX, item.halfY, item.height / 2],
  'rgba="0.65 0.67 0.60 1" group="0" contype="1" conaffinity="1"'
));
const boundaries = [
  ['west', [-floorX, 0, 0.25], [0.15, floorY, 0.25]],
  ['east', [floorX, 0, 0.25], [0.15, floorY, 0.25]],
  ['south', [0, -floorY, 0.25], [floorX, 0.15, 0.25]],
  ['north', [0, floorY, 0.25], [floorX, 0.15, 0.25]]
].map(([name, pos, size]) => geom(`campus-${name}-boundary`, pos, size, 'rgba="0.42 0.49 0.46 1"'));
const props = CAMPUS_PROPS.map((item) => geom(
  item.id, [item.x, item.y, item.height / 2], [item.halfX, item.halfY, item.height / 2],
  `rgba="${item.kind === 'planter' ? '0.50 0.53 0.46' : item.kind === 'charger' ? '0.05 0.42 0.32' : '0.23 0.37 0.42'} 1"`
));
const zones = ['charging', 'delivery'].map((name) => {
  const zone = CAMPUS_LAYOUT[name];
  return `    <site name="campus_${name}_zone" type="box" pos="${zone.x} ${zone.y} 0.005" size="${zone.halfX} ${zone.halfY} 0.001" rgba="${name === 'charging' ? '0.1 0.65 0.42' : '0.08 0.45 0.8'} 0.5" group="1" />`;
});
const start = xml.indexOf('    <geom name="west_boundary"');
const end = xml.indexOf('    <body name="agv_dock_anchor"');
if (start < 0 || end < start) throw new Error('The base AGV laboratory layout has changed');
xml = xml.slice(0, start) + [...boundaries, ...objects, ...props, ...zones].join('\n') + '\n' + xml.slice(end);
xml = xml.replace('model="rebot_rs_agv_v1"', 'model="rebot_rs_agv_campus"');
xml = xml.replace('size="4.2 3.2 0.04"', `size="${floorX} ${floorY} 0.04"`);
const spawn = CAMPUS_LAYOUT.spawn;
const spawnAttributes = `pos="${spawn.x} ${spawn.y} 0.136" quat="${vector([Math.cos(spawn.yaw / 2), 0, 0, Math.sin(spawn.yaw / 2)])}"`;
xml = xml.replace(/(<body name="base_link" )pos="[^"]*"/, `$1${spawnAttributes}`);
xml = xml.replace(/(<body name="agv_dock_anchor" mocap="true" )pos="[^"]*"/, `$1${spawnAttributes}`);
xml = xml.replace('<statistic center="0 0 0.3" extent="5.2"', '<statistic center="0 0 1" extent="20"');
const target = new URL('rs_agv_campus_scene.xml', models);
await writeFile(target, xml.replace('<mujoco ', '<!-- Generated by web_mujoco/scripts/build-campus-scene.mjs; edit campus-layout.js. -->\n<mujoco '));
console.log(`Generated ${fileURLToPath(target)}: ${CAMPUS_BUILDINGS.length} buildings, ${CAMPUS_PROPS.length} props`);
