#!/usr/bin/env python3
"""Generate the Forward-01 kinematic preview from the committed asset snapshot.

Source joint frames, mesh scales and inertials are retained. This scene deliberately
has no actuators or contact geoms; it is not a validated dynamics model.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path
import shlex
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT = ROOT / "assets/xense"
URDF = SNAPSHOT / "assets/assemblies/forward-01-flexiv-rizon4s/urdf/forward-01-flexiv-rizon4s-taccap.urdf"
MODELS = ROOT / "rebotarm_mujoco_rs/models"
SCENE = "flexiv_forward_01_scene.xml"
CONFIG = ROOT / "web_mujoco/src/flexiv-model.json"


def values(text, default):
    return [float(v) for v in text.split()] if text else default


def numbers(items):
    return " ".join(format(v, ".16g") for v in items)


def quaternion(rpy):
    roll, pitch, yaw = (v / 2 for v in rpy)
    cr, sr = math.cos(roll), math.sin(roll)
    cp, sp = math.cos(pitch), math.sin(pitch)
    cy, sy = math.cos(yaw), math.sin(yaw)
    return [cr * cp * cy + sr * sp * sy, sr * cp * cy - cr * sp * sy,
            cr * sp * cy + sr * cp * sy, cr * cp * sy - sr * sp * cy]


def pose(element):
    origin = element.find("origin")
    if origin is None:
        return {}
    return {"pos": origin.get("xyz", "0 0 0"),
            "quat": numbers(quaternion(values(origin.get("rpy"), [0, 0, 0])))}


def build():
    source = ET.parse(URDF).getroot()
    document = ET.Element("mujoco", model="flexiv_forward_01_taccap_preview")
    document.append(ET.Comment("Generated by tools/build_flexiv_model.py; kinematic preview, no contact validation."))
    ET.SubElement(document, "compiler", angle="radian", autolimits="true", inertiafromgeom="false", fusestatic="false")
    ET.SubElement(document, "option", timestep="0.002", gravity="0 0 -9.81")
    visual = ET.SubElement(document, "visual")
    ET.SubElement(visual, "global", offwidth="640", offheight="480")
    assets = ET.SubElement(document, "asset")
    world = ET.SubElement(document, "worldbody")
    ET.SubElement(world, "light", pos="2 -2 4", dir="-0.4 0.3 -1", diffuse="0.8 0.8 0.8")
    ET.SubElement(world, "geom", name="preview_floor", type="plane", size="4 4 0.1", pos="0 0 -0.005",
                  rgba="0.025 0.04 0.065 1", contype="0", conaffinity="0", group="0")

    outputs = {}
    material_names = set()
    mesh_names = set()
    derived = []

    def material(name, rgba):
        if name not in material_names:
            ET.SubElement(assets, "material", name=name, rgba=rgba, metallic="0.15", roughness="0.48")
            material_names.add(name)
        return name

    for entry in source.findall("material"):
        color = entry.find("color")
        if color is not None:
            material(entry.get("name"), color.get("rgba"))
    material("preview_default", "0.75 0.78 0.82 1")

    def add_mesh(path, scale):
        key = hashlib.sha256((path.relative_to(SNAPSHOT).as_posix() + ":" + scale).encode()).hexdigest()[:12]
        parts = []
        if path.suffix.lower() == ".obj":
            # Partition by upstream OBJ material rather than flattening the white
            # covers and metal housings into a single grey MuJoCo material.
            vertices, normals, texcoords, faces = [], [], [], {}
            current = "default"
            colors = {}
            text = path.read_text().replace("\\r\\n", "\n")
            for line in text.splitlines():
                fields = line.split()
                if not fields:
                    continue
                if fields[0] == "mtllib":
                    for filename in shlex.split(line)[1:]:
                        mtl = (path.parent / filename).read_text().replace("\\r\\n", "\n")
                        active = "default"
                        for row in mtl.splitlines():
                            words = row.split()
                            if words and words[0] == "newmtl":
                                active = words[1]
                            elif words and words[0] == "Kd":
                                colors[active] = " ".join(words[1:4]) + " 1"
                elif fields[0] == "v":
                    vertices.append(line)
                elif fields[0] == "vn":
                    normals.append(line)
                elif fields[0] == "vt":
                    texcoords.append(line)
                elif fields[0] == "usemtl":
                    current = fields[1]
                elif fields[0] == "f":
                    # Freeze indices to absolute values before grouping faces;
                    # source-relative negative indices refer to the current lists.
                    tokens = []
                    for token in fields[1:]:
                        indices = token.split("/")
                        for i, size in enumerate((len(vertices), len(texcoords), len(normals))):
                            if i < len(indices) and indices[i] and int(indices[i]) < 0:
                                indices[i] = str(size + int(indices[i]) + 1)
                        tokens.append("/".join(indices))
                    faces.setdefault(current, []).append("f " + " ".join(tokens))
            for index, (group, group_faces) in enumerate(sorted(faces.items())):
                name = f"flexiv_{key}_{index}"
                target = f"meshes/flexiv/{name}.obj"
                used = [set(), set(), set()]
                for face in group_faces:
                    for token in face.split()[1:]:
                        for dimension, value in enumerate(token.split("/")):
                            if value:
                                used[dimension].add(int(value))
                maps = [{old: new + 1 for new, old in enumerate(sorted(indices))} for indices in used]
                compact = []
                compact.extend(vertices[i - 1] for i in sorted(used[0]))
                for face in group_faces:
                    compact.append("f " + " ".join(
                        str(maps[0][int(token.split("/")[0])])
                        for token in face.split()[1:]
                    ))
                outputs[target] = ("\n".join(compact) + "\n").encode()
                parts.append((name, target, material(f"{name}_mat", colors.get(group, "0.75 0.78 0.82 1"))))
        else:
            name = f"flexiv_{key}"
            target = f"meshes/flexiv/{name}{path.suffix.lower()}"
            outputs[target] = path.read_bytes()
            parts.append((name, target, None))
        for name, target, _ in parts:
            if name not in mesh_names:
                ET.SubElement(assets, "mesh", name=name, file=target, scale=scale)
                mesh_names.add(name)
                derived.append({"source": path.relative_to(SNAPSHOT).as_posix(),
                                "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                "output": target, "sha256": hashlib.sha256(outputs[target]).hexdigest(),
                                "operation": "OBJ material partition; vertex coordinates and faces retained, indices compacted, normals regenerated by renderer" if path.suffix.lower() == ".obj" else "byte-identical copy"})
        return parts

    links = {entry.get("name"): entry for entry in source.findall("link")}
    parent_joints = {j.find("child").get("link"): j for j in source.findall("joint")}
    children = {}
    for joint in source.findall("joint"):
        children.setdefault(joint.find("parent").get("link"), []).append(joint.find("child").get("link"))
    joint_config = []
    bodies = {}

    def body_for(name, parent):
        entry = links[name]
        joint = parent_joints.get(name)
        body = ET.SubElement(parent, "body", name=name, **(pose(joint) if joint is not None else {}))
        bodies[name] = body
        inertial = entry.find("inertial")
        if inertial is not None and float(inertial.find("mass").get("value")) > 0:
            inertia = inertial.find("inertia")
            # fullinertia is expressed in the inertial frame; rotate it to body
            # coordinates explicitly since MuJoCo disallows quat + fullinertia.
            origin = inertial.find("origin")
            rpy = values(origin.get("rpy") if origin is not None else None, [0, 0, 0])
            import numpy as np
            w, x, y, z = quaternion(rpy)
            rotation = np.array([[1-2*(y*y+z*z), 2*(x*y-z*w), 2*(x*z+y*w)],
                                 [2*(x*y+z*w), 1-2*(x*x+z*z), 2*(y*z-x*w)],
                                 [2*(x*z-y*w), 2*(y*z+x*w), 1-2*(x*x+y*y)]])
            ixx, iyy, izz, ixy, ixz, iyz = [float(inertia.get(k)) for k in ("ixx", "iyy", "izz", "ixy", "ixz", "iyz")]
            tensor = rotation @ np.array([[ixx, ixy, ixz], [ixy, iyy, iyz], [ixz, iyz, izz]]) @ rotation.T
            ET.SubElement(body, "inertial", mass=inertial.find("mass").get("value"),
                          pos=origin.get("xyz", "0 0 0") if origin is not None else "0 0 0",
                          fullinertia=numbers([tensor[0,0], tensor[1,1], tensor[2,2], tensor[0,1], tensor[0,2], tensor[1,2]]))
        if joint is not None and joint.get("type") != "fixed":
            if joint.get("type") != "revolute":
                raise ValueError(f"Unsupported joint: {joint.attrib}")
            limits = joint.find("limit")
            axis = joint.find("axis").get("xyz")
            ET.SubElement(body, "joint", name=joint.get("name"), type="hinge", axis=axis,
                          range=f"{limits.get('lower')} {limits.get('upper')}")
            config = {"name": joint.get("name"), "min": float(limits.get("lower")), "max": float(limits.get("upper"))}
            mimic = joint.find("mimic")
            if mimic is not None:
                config["mimic"] = {"joint": mimic.get("joint"), "multiplier": float(mimic.get("multiplier", "1")), "offset": float(mimic.get("offset", "0"))}
            joint_config.append(config)
        for index, visual_entry in enumerate(entry.findall("visual")):
            geom = visual_entry.find("geometry")
            mesh = geom.find("mesh")
            if mesh is None:
                raise ValueError(f"Expected mesh visual on {name}")
            path = (URDF.parent / mesh.get("filename")).resolve()
            parts = add_mesh(path, mesh.get("scale", "1 1 1"))
            mat = visual_entry.find("material")
            color = mat.find("color") if mat is not None else None
            fallback = mat.get("name") if mat is not None else "preview_default"
            if color is not None:
                fallback = material(f"{name}_{index}_mat", color.get("rgba"))
            for part_index, (mesh_name, _, source_material) in enumerate(parts):
                ET.SubElement(body, "geom", name=f"{name}_visual_{index}_{part_index}", type="mesh", mesh=mesh_name,
                              material=source_material or fallback, group="1", contype="0", conaffinity="0", mass="0", **pose(visual_entry))
        for child in children.get(name, []):
            body_for(child, body)

    for name in links:
        if name not in parent_joints:
            body_for(name, world)

    # Optical +Z forward/+Y down -> render -Z forward/+Y up: local Rx(pi).
    cameras = []
    for side in ("left", "right"):
        optical = f"{side}_tool_taccap_camera_optical_link"
        ET.SubElement(bodies[optical], "camera", name=f"{side}_wrist_rgb", quat="0 1 0 0", fovy="60")
        cameras.append({"id": side, "name": f"{side}_wrist_rgb", "opticalLink": optical,
                        "width": 640, "height": 480, "fovy": 60, "calibrated": False})

    equality = ET.SubElement(document, "equality")
    for joint in joint_config:
        if "mimic" in joint:
            mimic = joint["mimic"]
            ET.SubElement(equality, "joint", joint1=joint["name"], joint2=mimic["joint"],
                          polycoef=f"{mimic['offset']} {mimic['multiplier']} 0 0 0")

    start = json.loads((URDF.parents[1] / "config/start_pose.taccap.json").read_text())
    homes = {}
    for side in ("left", "right"):
        homes.update({f"{side}_joint{i + 1}": math.radians(value) for i, value in enumerate(start["values"][f"{side}_arm"])})
        homes[f"{side}_tool_taccap_right_finger_joint"] = math.radians(start["values"][f"{side}_gripper"][0])
    for joint in joint_config:
        mimic = joint.get("mimic")
        joint["home"] = homes[mimic["joint"]] * mimic["multiplier"] + mimic["offset"] if mimic else homes[joint["name"]]
    config = {"id": "forward-01-flexiv-rizon4s-taccap", "sceneXml": SCENE, "mode": "kinematic",
              "joints": joint_config, "cameras": cameras, "sourceUrdfSha256": hashlib.sha256(URDF.read_bytes()).hexdigest()}
    ET.indent(document)
    outputs[SCENE] = ET.tostring(document, encoding="utf-8", xml_declaration=True) + b"\n"
    return outputs, config, derived


def main(check=False):
    outputs, config, derived = build()
    products = {MODELS / name: content for name, content in outputs.items()}
    products[CONFIG] = (json.dumps(config, indent=2) + "\n").encode()
    products[ROOT / "assets/xense/derived-manifest.json"] = (json.dumps({"generator": "tools/build_flexiv_model.py", "scope": "Kinematic visualization; source collision meshes are retained only in the snapshot. Camera fovy=60 degrees is an uncalibrated preview setting.", "meshes": derived}, indent=2) + "\n").encode()
    for path, content in products.items():
        if check:
            if not path.is_file() or path.read_bytes() != content:
                raise RuntimeError(f"Regenerate {path.relative_to(ROOT)}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    print(f"{'Checked' if check else 'Generated'} {SCENE}: {len(config['joints'])} joints, {len(config['cameras'])} wrist cameras, {len(derived)} meshes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    main(parser.parse_args().check)
